package org.example.export;

import java.time.LocalDateTime;
import java.time.format.DateTimeFormatter;
import java.util.LinkedHashMap;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Set;
import java.util.logging.Logger;

import org.example.model.RelacionDetectada;

/**
 * Generates PlantUML class diagrams from detected relations.
 */
public class PlantUMLGenerator {
    
    private static final Logger logger = Logger.getLogger(PlantUMLGenerator.class.getName());
    private static final DateTimeFormatter DATE_FORMAT = DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm:ss");
    
    // Package colors for visual grouping
    private static final String[] PACKAGE_COLORS = {
        "#FFEFD5", "#E6E6FA", "#F0FFF0", "#FFF0F5", "#F5F5DC", 
        "#E0FFFF", "#FFFACD", "#FFE4E1", "#F0F8FF", "#FDF5E6"
    };
    
    /**
     * Generates PlantUML diagram content from relations.
     * 
     * @param relations the relations to include
     * @param options export options
     * @return the generated PlantUML content
     */
    public String generate(List<RelacionDetectada> relations, ExportOptions options) {
        if (relations == null || relations.isEmpty()) {
            return generateEmpty();
        }
        
        StringBuilder sb = new StringBuilder();
        
        // Header
        sb.append("@startuml\n");
        sb.append("' Generated by Intelligent Relation Analyzer\n");
        sb.append("' Date: ").append(LocalDateTime.now().format(DATE_FORMAT)).append("\n");
        sb.append("' Relations: ").append(relations.size()).append("\n\n");
        
        // Styling
        sb.append("skinparam classAttributeIconSize 0\n");
        sb.append("skinparam classFontStyle bold\n");
        sb.append("hide empty members\n\n");
        
        // Extract and declare entities
        Set<String> entities = extractEntities(relations);
        
        if (options.colorByPackage()) {
            generateEntitiesGroupedByPackage(sb, entities);
        } else {
            generateEntitiesSimple(sb, entities);
        }
        sb.append("\n");
        
        // Generate relationships
        for (RelacionDetectada rel : relations) {
            sb.append(generateRelationship(rel, options));
        }
        
        sb.append("\n@enduml\n");
        
        logger.info(() -> "Generated PlantUML diagram with " + entities.size() + 
            " entities and " + relations.size() + " relations");
        
        return sb.toString();
    }

    /**
     * Extracts unique entity names from relations.
     * 
     * @param relations the list of relations
     * @return set of unique entity names
     */
    Set<String> extractEntities(List<RelacionDetectada> relations) {
        Set<String> entities = new LinkedHashSet<>();
        for (RelacionDetectada rel : relations) {
            entities.add(rel.getOrigen());
            entities.add(rel.getDestino());
        }
        return entities;
    }
    
    /**
     * Generates simple class declarations without grouping.
     */
    private void generateEntitiesSimple(StringBuilder sb, Set<String> entities) {
        for (String entity : entities) {
            sb.append("class ").append(entity).append("\n");
        }
    }
    
    /**
     * Generates class declarations grouped by package with colors.
     * Entities are grouped by their package prefix (if present).
     */
    private void generateEntitiesGroupedByPackage(StringBuilder sb, Set<String> entities) {
        Map<String, Set<String>> packageGroups = groupEntitiesByPackage(entities);
        
        int colorIndex = 0;
        for (Map.Entry<String, Set<String>> entry : packageGroups.entrySet()) {
            String packageName = entry.getKey();
            Set<String> packageEntities = entry.getValue();
            
            if (packageName.isEmpty()) {
                // No package - just declare classes
                for (String entity : packageEntities) {
                    sb.append("class ").append(entity).append("\n");
                }
            } else {
                // Group in a package with color
                String color = PACKAGE_COLORS[colorIndex % PACKAGE_COLORS.length];
                sb.append("package \"").append(packageName).append("\" ").append(color).append(" {\n");
                for (String entity : packageEntities) {
                    String simpleName = getSimpleName(entity);
                    sb.append("  class ").append(simpleName).append("\n");
                }
                sb.append("}\n");
                colorIndex++;
            }
        }
    }
    
    /**
     * Groups entities by their package prefix.
     * 
     * @param entities set of entity names (may include package prefix)
     * @return map of package name to entities in that package
     */
    Map<String, Set<String>> groupEntitiesByPackage(Set<String> entities) {
        Map<String, Set<String>> groups = new LinkedHashMap<>();
        
        for (String entity : entities) {
            String packageName = extractPackage(entity);
            groups.computeIfAbsent(packageName, k -> new LinkedHashSet<>()).add(entity);
        }
        
        return groups;
    }
    
    /**
     * Extracts package name from a fully qualified class name.
     * Returns empty string if no package.
     */
    private String extractPackage(String className) {
        int lastDot = className.lastIndexOf('.');
        return lastDot > 0 ? className.substring(0, lastDot) : "";
    }
    
    /**
     * Gets the simple class name from a potentially qualified name.
     */
    private String getSimpleName(String className) {
        int lastDot = className.lastIndexOf('.');
        return lastDot > 0 ? className.substring(lastDot + 1) : className;
    }
    
    /**
     * Generates a PlantUML relationship line with field names and bidirectional support.
     * 
     * @param rel the relation to generate
     * @param options export options
     * @return the PlantUML relationship line
     */
    String generateRelationship(RelacionDetectada rel, ExportOptions options) {
        StringBuilder sb = new StringBuilder();
        
        String origen = getSimpleName(rel.getOrigen());
        String destino = getSimpleName(rel.getDestino());
        
        // Get cardinality notation
        String[] cardinality = mapRelationToCardinality(rel.getTipo());
        String sourceCard = cardinality[0];
        String targetCard = cardinality[1];
        
        // Build relationship line with cardinality
        sb.append(origen);
        sb.append(" \"").append(sourceCard).append("\"");
        
        // Arrow direction based on bidirectional flag
        if (rel.isBidirectional()) {
            sb.append(" -- ");
        } else {
            sb.append(" --> ");
        }
        
        sb.append("\"").append(targetCard).append("\" ");
        sb.append(destino);
        
        // Add label with field name or relation type
        sb.append(" : ");
        String label = buildRelationshipLabel(rel, options);
        sb.append(label);
        
        sb.append("\n");
        return sb.toString();
    }
    
    /**
     * Builds the relationship label including field name and optional confidence.
     */
    private String buildRelationshipLabel(RelacionDetectada rel, ExportOptions options) {
        StringBuilder label = new StringBuilder();
        
        // Use mappedBy field name if available, otherwise use relation type
        if (rel.getMappedBy() != null && !rel.getMappedBy().isEmpty()) {
            label.append(rel.getMappedBy());
        } else {
            // Generate a field name from destination class (lowercase first letter)
            String fieldName = generateFieldName(rel.getDestino(), rel.getTipo());
            label.append(fieldName);
        }
        
        // Add bidirectional indicator
        if (rel.isBidirectional()) {
            label.append(" <>");
        }
        
        // Optionally show confidence
        if (options.showConfidence()) {
            label.append(String.format(Locale.ROOT, " (%.0f%%)", rel.getConfianza() * 100));
        }
        
        return label.toString();
    }
    
    /**
     * Generates a field name from the destination class and relation type.
     * For *ToMany relations, pluralizes the name.
     */
    private String generateFieldName(String destino, String tipo) {
        String simpleName = getSimpleName(destino);
        // Lowercase first letter
        String fieldName = simpleName.substring(0, 1).toLowerCase(Locale.ROOT) + simpleName.substring(1);
        
        // Pluralize for *ToMany relations
        if (tipo.endsWith("ToMany")) {
            fieldName = pluralize(fieldName);
        }
        
        return fieldName;
    }
    
    /**
     * Simple pluralization - adds 's' or 'es' as appropriate.
     */
    private String pluralize(String word) {
        if (word.endsWith("s") || word.endsWith("x") || word.endsWith("ch") || word.endsWith("sh")) {
            return word + "es";
        } else if (word.endsWith("y") && word.length() > 1 && !isVowel(word.charAt(word.length() - 2))) {
            return word.substring(0, word.length() - 1) + "ies";
        }
        return word + "s";
    }
    
    private boolean isVowel(char c) {
        return "aeiouAEIOU".indexOf(c) >= 0;
    }
    
    /**
     * Maps relation type to PlantUML cardinality notation.
     * Returns array of [sourceCardinality, targetCardinality].
     */
    String[] mapRelationToCardinality(String tipo) {
        return switch (tipo) {
            case "OneToOne" -> new String[]{"1", "1"};
            case "OneToMany" -> new String[]{"1", "*"};
            case "ManyToOne" -> new String[]{"*", "1"};
            case "ManyToMany" -> new String[]{"*", "*"};
            default -> new String[]{"", ""};
        };
    }
    
    /**
     * Generates an empty diagram.
     */
    private String generateEmpty() {
        return """
            @startuml
            ' Generated by Intelligent Relation Analyzer
            ' No relations to display
            note "No relations found" as N1
            @enduml
            """;
    }
}

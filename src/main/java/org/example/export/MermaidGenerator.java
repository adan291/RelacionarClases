package org.example.export;

import java.time.LocalDateTime;
import java.time.format.DateTimeFormatter;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Locale;
import java.util.Set;
import java.util.logging.Logger;

import org.example.model.RelacionDetectada;

/**
 * Generates Mermaid ER diagrams from detected relations.
 */
public class MermaidGenerator {
    
    private static final Logger logger = Logger.getLogger(MermaidGenerator.class.getName());
    private static final DateTimeFormatter DATE_FORMAT = DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm:ss");
    
    /**
     * Generates Mermaid diagram content from relations.
     * 
     * @param relations the relations to include
     * @param options export options
     * @return the generated Mermaid content
     */
    public String generate(List<RelacionDetectada> relations, ExportOptions options) {
        if (relations == null || relations.isEmpty()) {
            return generateEmpty();
        }
        
        StringBuilder sb = new StringBuilder();
        
        // Header with metadata comment
        sb.append("```mermaid\n");
        sb.append("---\n");
        sb.append("title: Entity Relationships\n");
        sb.append("---\n");
        sb.append("erDiagram\n");
        sb.append("    %% Generated by Intelligent Relation Analyzer\n");
        sb.append("    %% Date: ").append(LocalDateTime.now().format(DATE_FORMAT)).append("\n");
        sb.append("    %% Relations: ").append(relations.size()).append("\n\n");
        
        // Generate relationships
        Set<String> entities = new LinkedHashSet<>();
        for (RelacionDetectada rel : relations) {
            entities.add(rel.getOrigen());
            entities.add(rel.getDestino());
            sb.append("    ").append(generateRelationship(rel, options)).append("\n");
        }
        
        sb.append("```\n");
        
        logger.info(() -> "Generated Mermaid diagram with " + entities.size() + 
            " entities and " + relations.size() + " relations");
        
        return sb.toString();
    }
    
    /**
     * Generates a Mermaid relationship line.
     */
    private String generateRelationship(RelacionDetectada rel, ExportOptions options) {
        String origen = toMermaidName(rel.getOrigen());
        String destino = toMermaidName(rel.getDestino());
        String notation = mapRelationToNotation(rel.getTipo());
        
        StringBuilder label = new StringBuilder(rel.getTipo());
        if (options.showConfidence()) {
            label.append(String.format(Locale.ROOT, " %.0f%%", rel.getConfianza() * 100));
        }
        
        return String.format("%s %s %s : \"%s\"", origen, notation, destino, label);
    }
    
    /**
     * Converts class name to Mermaid-compatible UPPER_SNAKE_CASE format.
     * Examples: "User" -> "USER", "OrderItem" -> "ORDER_ITEM", "HTTPClient" -> "HTTP_CLIENT"
     */
    String toMermaidName(String className) {
        if (className == null || className.isEmpty()) {
            return "";
        }
        
        // Get simple name (remove package prefix if present)
        String simpleName = className;
        int lastDot = className.lastIndexOf('.');
        if (lastDot >= 0) {
            simpleName = className.substring(lastDot + 1);
        }
        
        // Convert camelCase/PascalCase to UPPER_SNAKE_CASE
        StringBuilder result = new StringBuilder();
        for (int i = 0; i < simpleName.length(); i++) {
            char c = simpleName.charAt(i);
            
            if (Character.isUpperCase(c) && i > 0) {
                // Check if previous char was lowercase or if next char is lowercase (for acronyms)
                char prev = simpleName.charAt(i - 1);
                boolean nextIsLower = (i + 1 < simpleName.length()) && 
                                      Character.isLowerCase(simpleName.charAt(i + 1));
                
                if (Character.isLowerCase(prev) || nextIsLower) {
                    result.append('_');
                }
            }
            
            if (Character.isLetterOrDigit(c)) {
                result.append(Character.toUpperCase(c));
            } else {
                result.append('_');
            }
        }
        
        return result.toString();
    }
    
    /**
     * Maps relation type to Mermaid ER notation.
     * ||--|| : one to one
     * ||--o{ : one to many
     * }o--|| : many to one
     * }o--o{ : many to many
     */
    private String mapRelationToNotation(String tipo) {
        return switch (tipo) {
            case "OneToOne" -> "||--||";
            case "OneToMany" -> "||--o{";
            case "ManyToOne" -> "}o--||";
            case "ManyToMany" -> "}o--o{";
            default -> "--";
        };
    }
    
    /**
     * Generates an empty diagram.
     */
    private String generateEmpty() {
        return """
            ```mermaid
            erDiagram
                %% No relations to display
            ```
            """;
    }
}
